import type { Product } from "../types";

/** Seed-only review text; lib/server/store/seed.ts turns each one into a Review linked to a demo order. */
export interface SeedReview {
  customerName: string;
  rating: number;
  comment: string;
  date: string;
}

export type ProductSeed = Omit<Product, "id" | "status" | "rejectionReason" | "createdAt" | "updatedAt"> & {
  reviews: SeedReview[];
};

type Optional = "reviews" | "isEcoFriendly" | "isHeritage" | "isCustomizable" | "tags" | "styles";
type Draft = Omit<ProductSeed, Optional> & Partial<Pick<ProductSeed, Optional>>;

function product(d: Draft): ProductSeed {
  return {
    reviews: [],
    isEcoFriendly: false,
    isHeritage: false,
    isCustomizable: Boolean(d.customization?.length),
    tags: [],
    styles: [],
    ...d,
  };
}

